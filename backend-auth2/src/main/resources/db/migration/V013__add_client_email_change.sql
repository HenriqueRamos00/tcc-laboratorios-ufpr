CREATE TABLE CLIENT_EMAIL_CHANGE (
  CLIENT_ACCOUNT_ID NUMBER(19) NOT NULL,
  APPLICATION_ID NUMBER(19) NOT NULL,
  NEW_EMAIL VARCHAR2(254 CHAR),
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE,
  EXPIRES_AT TIMESTAMP(6) WITH TIME ZONE,
  CURRENT_EMAIL_CONFIRMED NUMBER(1) DEFAULT 0 NOT NULL,
  NEW_EMAIL_CONFIRMED NUMBER(1) DEFAULT 0 NOT NULL,
  CREDENTIAL_VERSION NUMBER(19) DEFAULT 0 NOT NULL,
  WINDOW_STARTED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  REQUEST_COUNT NUMBER(2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_CLIENT_EMAIL_CHANGE PRIMARY KEY (CLIENT_ACCOUNT_ID),
  CONSTRAINT FK_CLIENT_EMAIL_CHANGE_ACCOUNT FOREIGN KEY (CLIENT_ACCOUNT_ID)
    REFERENCES CLIENT_ACCOUNT (ID),
  CONSTRAINT FK_CLIENT_EMAIL_CHANGE_APPLICATION FOREIGN KEY (APPLICATION_ID)
    REFERENCES APPLICATION (ID),
  CONSTRAINT CK_CLIENT_EMAIL_CHANGE_CURRENT CHECK (CURRENT_EMAIL_CONFIRMED IN (0, 1)),
  CONSTRAINT CK_CLIENT_EMAIL_CHANGE_NEW CHECK (NEW_EMAIL_CONFIRMED IN (0, 1)),
  CONSTRAINT CK_CLIENT_EMAIL_CHANGE_COUNT CHECK (REQUEST_COUNT BETWEEN 0 AND 3),
  CONSTRAINT CK_CLIENT_EMAIL_CHANGE_PENDING CHECK (
    (NEW_EMAIL IS NULL AND CREATED_AT IS NULL AND EXPIRES_AT IS NULL)
    OR (NEW_EMAIL IS NOT NULL AND CREATED_AT IS NOT NULL AND EXPIRES_AT IS NOT NULL)
  )
);

